#!/usr/bin/env python3
"""
Apply the cheap, data-only fixes found by scripts/verify_question_bank.py.

Deterministic and idempotent: random choices are derived from SHA-256 of the
item id, so repeated runs produce identical files. Only `payload`, `choices`
and (for 20 gridPath items) the on-screen `prompt` are edited. `spokenForm`,
`answer` and `audioID` are never touched, so no narration text changes and no
audio has to be regenerated by this script.

Fixes, in the order of the report:
  gridPath        path leaves the grid -> shift the start cell; add the object
                  layout the screen needs; put the moves into the on-screen
                  prompt where it omitted them
  dataPlot        ties for "most" -> raise the keyed bar by 1; "how many more X
                  than Y" with X < Y -> swap the two bar values
  buildShape      distractor "two triangles" can build a rectangle -> "two pentagons"
  positionWords   two objects in one cell -> move the non-answer object
  rotateToMatch   options that look identical -> give them distinct rotations;
                  mirrored copies of mirror-symmetric shapes -> plain rotations
  netPreview      rebuild options so exactly one net folds; add drawable `cells`
  symmetryMirror  add drawable `halfCells` / option `cells` (mirror pictures)
  shapeHunt       shapes stacked in one cell -> spread onto free cells
"""

from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACK = ROOT / "MathQuestKids/Content/content-pack-v1.json"
BANK = ROOT / "MathQuestKids/Content/spatial-question-bank-v2.json"

# --- shared reference data (the verifier imports these) -------------------------------

NET_CELLS = {
    "cross net": [".#..", "####", ".#.."],
    "T net": [".#..", "####", "..#."],
    "zigzag net": ["##..", ".##.", "..##"],
    "strip net": ["######"],
    "missing-face net": [".#..", "####"],
    "overlap net": ["###", "###"],
}
NET_DESCRIPTION = {
    "cross net": "six squares connected in a cross shape",
    "T net": "four squares in a row with one above and one below",
    "zigzag net": "six squares connected in a zigzag that can fold",
    "strip net": "six squares in one long strip",
    "missing-face net": "only five squares",
    "overlap net": "six squares that overlap when folded",
}
NON_FOLDING = ["strip net", "missing-face net", "overlap net"]

# Left halves (4 columns) of vertically symmetric pictures; the full picture is half + reversed half.
# For horizontal mirror lines the picture is transposed (it lies on its side).
ART = {
    "heart": ["·##·", "####", "####", "·###", "··##", "···#"],
    "butterfly": ["##··", "###·", "####", "···#", "###·", "##··", "·#··"],
    "star": ["···#", "···#", "··##", "####", "·###", "··##", "·#·#", "#···"],
    "leaf": ["···#", "··##", "·###", "####", "####", "·###", "··##", "···#", "···#", "··#·"],
    "square pattern": ["####", "#·##", "#·#·", "####", "#···", "#·#·"],
    "rocket badge": ["···#", "··##", "·###", "·###", "####", "#·##", "··#·", "·#··"],
}

# How the app draws each rotate shape: step = turn angle after which it looks identical,
# mirror = True if it has a mirror line (a mirrored copy equals a rotation of it).
ROT_SHAPES = {
    "triangle": (360, False),    # drawn as a right triangle (chiral)
    "rectangle": (180, True),
    "diamond": (180, True),
    "pentagon": (72, True),
    "trapezoid": (360, False),   # drawn as a right trapezoid (chiral)
    "arrow": (360, True),
    "L shape": (360, False),
    "T shape": (360, True),
}


def h(*parts) -> int:
    return int(hashlib.sha256("|".join(str(p) for p in parts).encode()).hexdigest(), 16)


def free_cell(item_id, salt, cols, rows, taken, forbidden=()):
    cells = [(x, y) for y in range(rows) for x in range(cols) if (x, y) not in taken and (x, y) not in forbidden]
    cells.sort(key=lambda c: h(item_id, salt, c))
    return cells[0]


def rev_cols(rows):
    return [r[::-1] for r in rows]


def rev_rows(rows):
    return rows[::-1]


def transpose(rows):
    return ["".join(r[i] for r in rows) for i in range(len(rows[0]))]


def art_half(name, axis):
    half = [r.replace("·", ".") for r in ART[name]]
    return half if axis == "vertical" else transpose(half)


# --- fixes ----------------------------------------------------------------------------

def fix_grid_path(it, log):
    p = it["payload"]
    cols, rows = p["gridSize"]["columns"], p["gridSize"]["rows"]
    s, d = p["startPosition"], p["delta"]
    sx, sy = s["x"], s["y"]
    for axis, n in (("x", cols), ("y", rows)):
        start = sx if axis == "x" else sy
        delta = d[axis]
        end = start + delta
        if end < 0:
            start -= end
        elif end >= n:
            start -= end - (n - 1)
        if axis == "x":
            sx = start
        else:
            sy = start
    if (sx, sy) != (s["x"], s["y"]):
        log["gridPath.start_shifted"] += 1
    p["startPosition"] = {"x": sx, "y": sy}
    p["targetPosition"] = {"x": sx + d["x"], "y": sy + d["y"]}
    assert 0 <= sx < cols and 0 <= sy < rows and 0 <= p["targetPosition"]["x"] < cols and 0 <= p["targetPosition"]["y"] < rows
    assert (d["x"], d["y"]) != (0, 0)

    taken = {(sx, sy), (p["targetPosition"]["x"], p["targetPosition"]["y"])}
    layout = [{"name": p["start"], "x": sx, "y": sy},
              {"name": p["targetObject"], "x": p["targetPosition"]["x"], "y": p["targetPosition"]["y"]}]
    for name in it["choices"]:
        if name == p["targetObject"] or name == p["start"]:
            continue
        x, y = free_cell(it["id"], name, cols, rows, taken)
        taken.add((x, y))
        layout.append({"name": name, "x": x, "y": y})
    if p.get("objects") != layout:
        log["gridPath.layout_written"] += 1
    p["objects"] = layout

    if p["moves"] not in it["prompt"]:
        new = it["prompt"].replace(f"from {p['start']}.", f"from {p['start']}: {p['moves']}.")
        assert new != it["prompt"], it["prompt"]
        it["prompt"] = new
        log["gridPath.prompt_moves_added"] += 1


def fix_data_plot(it, log):
    p = it["payload"]
    labs, vals = p["barLabels"], p["barValues"]
    prompt = it["prompt"]
    if prompt.startswith(("Which has the most", "Which fraction has the most")):
        mx = max(vals)
        if vals.count(mx) > 1:
            vals[labs.index(it["answer"])] = mx + 1
            log["dataPlot.tie_broken"] += 1
    else:
        m = re.fullmatch(r"How many more (\w+) than (\w+)\?", prompt)
        if m:
            a, b = labs.index(m.group(1)), labs.index(m.group(2))
            if vals[a] - vals[b] != int(it["answer"]):
                vals[a], vals[b] = vals[b], vals[a]
                log["dataPlot.values_swapped"] += 1
            assert vals[a] - vals[b] == int(it["answer"]), it["id"]


def fix_build_shape(it, log):
    p = it["payload"]
    if p["targetShape"] == "rectangle" and "two triangles" in it["choices"]:
        it["choices"] = ["two pentagons" if c == "two triangles" else c for c in it["choices"]]
        p["distractorPieces"] = ["two pentagons" if c == "two triangles" else c for c in p["distractorPieces"]]
        log["buildShape.distractor_replaced"] += 1


def fix_position_words(it, log):
    p = it["payload"]
    cols, rows = p["gridSize"]["columns"], p["gridSize"]["rows"]
    objs = p["objects"]
    anchor = next(o for o in objs if o["name"] == p["anchor"])
    offsets = {"above": [(0, -1)], "below": [(0, 1)], "left of": [(-1, 0)], "right of": [(1, 0)],
               "beside": [(-1, 0), (1, 0)]}[p["relation"]]
    valid = {(anchor["x"] + dx, anchor["y"] + dy) for dx, dy in offsets}
    by_cell = {}
    for o in objs:
        by_cell.setdefault((o["x"], o["y"]), []).append(o)
    for cell, group in sorted(by_cell.items()):
        if len(group) < 2:
            continue
        keep_first = [o for o in group if o["name"] in (p["anchor"], it["answer"])]
        movable = [o for o in group if o not in keep_first]
        if not keep_first:
            movable = group[1:]
        for o in movable:
            taken = {(q["x"], q["y"]) for q in objs}
            o["x"], o["y"] = free_cell(it["id"], o["name"], cols, rows, taken, forbidden=valid)
            log["positionWords.object_moved"] += 1


def fix_rotate(it, log):
    p = it["payload"]
    step, mirror_sym = ROT_SHAPES[p["shape"]]
    opts = p["options"]
    ans_rot = p["rotationDegrees"] % 360

    def key(o):
        mirrored = bool(o["mirrored"]) and not mirror_sym
        return ((o["rotation"] % 360) % step, mirrored)

    if mirror_sym:
        for o in opts:
            if o["mirrored"]:
                o["mirrored"] = False
                log["rotate.mirror_removed"] += 1
    answer_key = (ans_rot % step, False)
    seen = {answer_key}
    for o in opts:
        if o["label"] == it["answer"]:
            continue
        while key(o) in seen:
            used = {(q["rotation"] % 360) for q in opts}
            cands = [r for r in range(0, 360, 45) if r not in used and ((r % step, bool(o["mirrored"]) and not mirror_sym) not in seen)]
            cands.sort(key=lambda r: h(it["id"], o["label"], r))
            o["rotation"] = cands[0]
            log["rotate.rotation_changed"] += 1
        seen.add(key(o))


def fix_net(it, log):
    p = it["payload"]
    opts = p["options"]
    flagged = [o for o in opts if o["foldsToCube"]]
    assert len(flagged) == 1 and flagged[0]["label"] == it["answer"], it["id"]
    used = {flagged[0]["pattern"]}
    for o in opts:
        if o is flagged[0]:
            continue
        if o["pattern"] in NON_FOLDING and o["pattern"] not in used:
            used.add(o["pattern"])
            continue
        spare = [n for n in NON_FOLDING if n not in used and n not in {q["pattern"] for q in opts if q is not o}]
        pat = spare[0] if spare else next(n for n in NON_FOLDING if n not in used)
        if o["pattern"] != pat:
            log["net.option_replaced"] += 1
        o["pattern"] = pat
        used.add(pat)
    for o in opts:
        o["description"] = NET_DESCRIPTION[o["pattern"]]
        o["foldsToCube"] = o["pattern"] not in NON_FOLDING
        o["cells"] = NET_CELLS[o["pattern"]]
    assert sum(o["foldsToCube"] for o in opts) == 1 and len({o["pattern"] for o in opts}) == 4, it["id"]


def fix_symmetry(it, log):
    p = it["payload"]
    axis = p["axis"]
    half = art_half(p["object"], axis)
    if axis == "vertical":
        correct, d1, d2, d3 = rev_cols(half), half, rev_rows(half), rev_rows(rev_cols(half))
    else:
        correct, d1, d2, d3 = rev_rows(half), half, rev_cols(half), rev_cols(rev_rows(half))
    cands = [correct, d1, d2, d3]
    assert len({tuple(c) for c in cands}) == 4, f"art for {p['object']} cannot give 4 distinct options"
    others = [d1, d2, d3]
    shift = h(it["id"]) % 3
    others = others[shift:] + others[:shift]
    it_others = iter(others)
    p["halfCells"] = half
    for o in p["options"]:
        o["cells"] = correct if o["mirrorsCorrectly"] else next(it_others)
    log["symmetry.cells_written"] += 1


def fix_shape_hunt(it, log):
    p = it["payload"]
    cols, rows = p["gridSize"]["columns"], p["gridSize"]["rows"]
    seen = set()
    for s in p["scene"]:
        cell = (s["x"], s["y"])
        if cell in seen:
            taken = {(q["x"], q["y"]) for q in p["scene"]}
            s["x"], s["y"] = free_cell(it["id"], s["shape"] + s["color"], cols, rows, taken)
            log["shapeHunt.shape_moved"] += 1
            cell = (s["x"], s["y"])
        seen.add(cell)


FIXERS = {"gridPath": fix_grid_path, "dataPlot": fix_data_plot, "buildShape": fix_build_shape,
          "positionWords": fix_position_words, "rotateToMatch": fix_rotate, "netPreview": fix_net,
          "symmetryMirror": fix_symmetry, "shapeHunt": fix_shape_hunt}


def main():
    from collections import Counter
    log = Counter()
    pack = json.loads(PACK.read_text(encoding="utf-8"))
    for it in pack["itemTemplates"]:
        fx = FIXERS.get(it["format"])
        if fx:
            fx(it, log)
    PACK.write_text(json.dumps(pack, indent=2, ensure_ascii=True) + "\n", encoding="utf-8")

    # keep the draft spatial bank file identical to what the app loads
    byid = {it["id"]: it for it in pack["itemTemplates"]}
    bank = json.loads(BANK.read_text(encoding="utf-8"))
    for b in bank["items"]:
        src = byid[b["id"]]
        for k in ("prompt", "answer", "choices", "payload", "spokenForm"):
            b[k] = src[k]
    BANK.write_text(json.dumps(bank, indent=2, ensure_ascii=True) + "\n", encoding="utf-8")

    for k, v in sorted(log.items()):
        print(f"{k:34s} {v}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
